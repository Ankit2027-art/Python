# 1. Arithmetic Operators
a = 10
b = 3
print("Arithmetic Operators:")
print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)
print("a // b =", a // b)
print("a % b =", a % b)
print("a ** b =", a ** b)

# 2. Assignment Operators
print("\nAssignment Operators:")
x = 5
x += 2
print("x += 2 ->", x)
x *= 3
print("x *= 3 ->", x)

# 3. Comparison Operators
print("\nComparison Operators:")
